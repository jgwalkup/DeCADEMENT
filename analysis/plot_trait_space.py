"""
plot_trait_space.py
===================
Visualize the trait space of a DeCA-DEMENT taxon pool generated by
generate_trait_pool.py. Produces a scatterplot with:

  X axis — Stress tolerance (S): combined constitutive + inducible HSP
            production rate, normalised by the theoretical maximum.
            HSP=0 taxa plot at S=0.

  Y axis — Acquisition (A): weighted combination of normalised enzyme
            investment (0.75) and normalised transporter investment (0.25),
            each normalised by their theoretical maxima derived from
            parameter bounds.

Axis maxima are read directly from parameters.csv and runtime.txt so they
stay in sync if parameter bounds change.

Usage
-----
    python analysis/plot_trait_space.py \\
        --trait-pool  taxon_output/trait_pool.csv \\
        --input-dir   input \\
        --output-dir  taxon_output

Options
-------
  --trait-pool      Path to trait_pool.csv from generate_trait_pool.py
  --input-dir       Directory containing parameters.csv and runtime.txt
                    (used to read normalisation bounds)
  --output-dir      Directory for saved figure (default: taxon_output)
  --runtime         runtime.txt filename inside --input-dir (default: runtime.txt)
  --enz-weight      Weight for enzyme component of A axis (default: 0.75)
  --upt-weight      Weight for transporter component of A axis (default: 0.25)
  --no-density      Suppress KDE contour overlay (shown by default)
  --show            Display figure interactively in addition to saving
"""

import argparse
import os
import sys
import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import matplotlib.colors as mcolors
from matplotlib.lines import Line2D


# ---------------------------------------------------------------------------
# Parameter loading
# ---------------------------------------------------------------------------

def load_bounds(input_dir, runtime_file='runtime.txt'):
    """
    Read normalisation bounds from parameters.csv and runtime.txt.
    Returns a dict with keys:
        enz_max   — theoretical max of (total_enz_consti + total_enz_induci)
        upt_max   — theoretical max of total_uptake_cost
        hsp_max   — theoretical max of (HSP_consti_rate + HSP_induci_rate)
    """
    params = pd.read_csv(
        os.path.join(input_dir, 'parameters.csv'),
        header=None, index_col=0
    )
    params.columns = [1]
    p = params[1].astype(float)

    runtime = pd.read_csv(
        os.path.join(input_dir, runtime_file),
        sep='\t', header=None, index_col=0
    )
    runtime.columns = [1]
    numeric_mask = pd.to_numeric(runtime[1], errors='coerce').notna()
    runtime = runtime.loc[numeric_mask].copy()
    runtime[1] = pd.to_numeric(runtime[1])

    enz_max = float(p['Enz_per_taxon_max']) * (
        float(p['Enz_Prod_max']) + float(p['Constit_Prod_max'])
    )
    upt_max = float(runtime.loc['n_uptake', 1]) * float(p['Uptake_C_cost_max'])
    hsp_max = float(p['HSP_Consti_Prod_max']) + float(p['HSP_Induci_Prod_max'])

    return {'enz_max': enz_max, 'upt_max': upt_max, 'hsp_max': hsp_max}


# ---------------------------------------------------------------------------
# Axis calculation
# ---------------------------------------------------------------------------

def compute_axes(trait_pool, bounds, enz_weight=0.75, upt_weight=0.25):
    """
    Add normalised S and A columns to trait_pool (in place) and return it.

    S = (HSP_consti_rate + HSP_induci_rate) / hsp_max
        [0 for HSP=0 taxa by construction of the trait pool]

    A = enz_weight  * (total_enz_consti + total_enz_induci) / enz_max
      + upt_weight  * total_uptake_cost / upt_max
    """
    tp = trait_pool.copy()

    tp['S'] = (tp['HSP_consti_rate'] + tp['HSP_induci_rate']) / bounds['hsp_max']

    enz_norm = (tp['total_enz_consti'] + tp['total_enz_induci']) / bounds['enz_max']
    upt_norm = tp['total_uptake_cost'] / bounds['upt_max']
    tp['A'] = enz_weight * enz_norm + upt_weight * upt_norm

    return tp


# ---------------------------------------------------------------------------
# Plotting
# ---------------------------------------------------------------------------

def plot_trait_space(tp, bounds, enz_weight, upt_weight,
                     show_density=True, output_dir='.'):
    """
    Produce and save the S–A scatterplot.
    """
    hsp0 = tp[tp.HSP_gene == 0]
    hsp1 = tp[tp.HSP_gene == 1]

    # Colour scheme: muted teal for non-producers, warm amber for producers
    c0 = '#4E9E9E'   # HSP=0
    c1 = '#D4813A'   # HSP=1
    alpha = 0.65
    size  = 28

    fig, ax = plt.subplots(figsize=(7, 6))

    # ── KDE density contours ────────────────────────────────────────────────
    if show_density and len(tp) >= 10:
        try:
            from scipy.stats import gaussian_kde
            a_range = np.linspace(tp['A'].min(), tp['A'].max(), 120)

            # HSP=0: all taxa sit at S=0, so KDE is 1D along A only.
            # Draw a horizontal density ribbon at S=0.
            if len(hsp0) >= 5:
                kde0 = gaussian_kde(hsp0['A'].values, bw_method='scott')
                density0 = kde0(a_range)
                # Normalise ribbon height to a fixed fraction of the S axis range
                ribbon_scale = 0.04
                density0_norm = density0 / density0.max() * ribbon_scale
                ax.fill_betweenx(a_range, 0, -density0_norm,
                                 color=c0, alpha=0.25, zorder=2)

            # HSP=1: full 2D KDE
            if len(hsp1) >= 5:
                s_range = np.linspace(hsp1['S'].min(), hsp1['S'].max(), 120)
                xy  = np.vstack([hsp1['S'], hsp1['A']])
                kde1 = gaussian_kde(xy, bw_method='scott')
                SS, AA = np.meshgrid(s_range, a_range)
                Z = kde1(np.vstack([SS.ravel(), AA.ravel()])).reshape(SS.shape)
                levels = np.percentile(Z[Z > 0], [25, 50, 75])
                ax.contour(SS, AA, Z, levels=levels,
                           colors=[c1], linewidths=0.8, alpha=0.45)
        except ImportError:
            pass   # scipy not available — skip contours silently

    # ── Scatter points ───────────────────────────────────────────────────────
    ax.scatter(hsp0['S'], hsp0['A'], c=c0, s=size, alpha=alpha,
               linewidths=0, label='HSP absent (S=0 by definition)', zorder=3)
    ax.scatter(hsp1['S'], hsp1['A'], c=c1, s=size, alpha=alpha,
               linewidths=0, label='HSP present', zorder=3)

    # ── Axes labels and formatting ───────────────────────────────────────────
    ax.set_xlabel(
        'Stress tolerance (S)\n'
        r'$S = (r_{HSP,consti} + r_{HSP,induci})\ /\ S_{max}$',
        fontsize=11
    )
    ax.set_ylabel(
        'Acquisition (A)\n'
        r'$A = 0.75 \cdot A_{enz} + 0.25 \cdot A_{upt}$',
        fontsize=11
    )
    ax.set_title('Trait space — DeCA-DEMENT taxon pool', fontsize=12, pad=10)

    # Axis limits with a little breathing room
    ax.set_xlim(-0.02, 1.05)
    ax.set_ylim(tp['A'].min() * 0.9, tp['A'].max() * 1.05)

    # Thin reference line at S=0 to visually separate non-producers
    ax.axvline(0, color='#bbbbbb', linewidth=0.8, linestyle='--', zorder=1)

    ax.spines[['top', 'right']].set_visible(False)
    ax.tick_params(labelsize=10)

    # ── Legend ───────────────────────────────────────────────────────────────
    legend_elements = [
        Line2D([0], [0], marker='o', color='w', markerfacecolor=c0,
               markersize=8, label=f'HSP absent  (n={len(hsp0)})'),
        Line2D([0], [0], marker='o', color='w', markerfacecolor=c1,
               markersize=8, label=f'HSP present (n={len(hsp1)})'),
    ]
    ax.legend(handles=legend_elements, frameon=False, fontsize=10,
              loc='upper left')

    # ── Annotation: normalisation bounds ────────────────────────────────────
    note = (
        f"Normalisation bounds (from parameters.csv / runtime.txt):\n"
        f"  $S_{{max}}$ = {bounds['hsp_max']:.4f}  "
        f"  $A_{{enz,max}}$ = {bounds['enz_max']:.4f}  "
        f"  $A_{{upt,max}}$ = {bounds['upt_max']:.4f}"
    )
    fig.text(0.01, 0.01, note, fontsize=7.5, color='#666666',
             va='bottom', ha='left')

    plt.tight_layout(rect=[0, 0.04, 1, 1])

    out_path = os.path.join(output_dir, 'trait_space.pdf')
    fig.savefig(out_path, dpi=200, bbox_inches='tight')
    print(f"Figure saved to: {out_path}")

    # Also save PNG for quick viewing
    png_path = os.path.join(output_dir, 'trait_space.png')
    fig.savefig(png_path, dpi=150, bbox_inches='tight')
    print(f"Figure saved to: {png_path}")

    return fig


# ---------------------------------------------------------------------------
# CLI
# ---------------------------------------------------------------------------

def main():
    parser = argparse.ArgumentParser(
        description="Plot S–A trait space for a DeCA-DEMENT taxon pool.",
        formatter_class=argparse.ArgumentDefaultsHelpFormatter,
    )
    parser.add_argument('--trait-pool',   type=str, required=True,
                        help='Path to trait_pool.csv')
    parser.add_argument('--input-dir',    type=str, default='input',
                        help='Directory containing parameters.csv and runtime.txt')
    parser.add_argument('--output-dir',   type=str, default='taxon_output',
                        help='Directory for saved figure')
    parser.add_argument('--runtime',      type=str, default='runtime.txt',
                        help='runtime.txt filename inside --input-dir')
    parser.add_argument('--enz-weight',   type=float, default=0.75,
                        help='Weight for enzyme component of A axis')
    parser.add_argument('--upt-weight',   type=float, default=0.25,
                        help='Weight for transporter component of A axis')
    parser.add_argument('--no-density',   action='store_true',
                        help='Suppress KDE contour overlay')
    parser.add_argument('--show',         action='store_true',
                        help='Display figure interactively')
    args = parser.parse_args()

    # Validate weights
    if not abs(args.enz_weight + args.upt_weight - 1.0) < 1e-6:
        print(f"ERROR: --enz-weight and --upt-weight must sum to 1.0 "
              f"(got {args.enz_weight} + {args.upt_weight} = "
              f"{args.enz_weight + args.upt_weight:.4f})")
        sys.exit(1)

    input_dir  = os.path.abspath(args.input_dir)
    output_dir = os.path.abspath(args.output_dir)
    os.makedirs(output_dir, exist_ok=True)

    trait_pool = pd.read_csv(args.trait_pool)
    print(f"Loaded {len(trait_pool)} taxa from {args.trait_pool}")

    bounds = load_bounds(input_dir, runtime_file=args.runtime)
    print(f"Normalisation bounds:")
    print(f"  S_max     = {bounds['hsp_max']:.4f}")
    print(f"  A_enz_max = {bounds['enz_max']:.4f}")
    print(f"  A_upt_max = {bounds['upt_max']:.4f}")

    tp = compute_axes(trait_pool, bounds,
                      enz_weight=args.enz_weight,
                      upt_weight=args.upt_weight)

    fig = plot_trait_space(
        tp, bounds,
        enz_weight=args.enz_weight,
        upt_weight=args.upt_weight,
        show_density=not args.no_density,
        output_dir=output_dir,
    )

    if args.show:
        plt.show()
    plt.close(fig)


if __name__ == '__main__':
    main()
