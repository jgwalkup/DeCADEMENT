"""
community_summary.py
====================
Compute community-level functional summaries for a single community directory
produced by assemble_communities.py. Reports:

  Enzyme coverage:
    - Total enzyme gene assignments across all taxa
    - Number of unique enzyme genes present in at least one taxon
    - Average number of enzyme genes per taxon
    - Number of enzymes targeting each substrate (requires --input-dir
      for the ReqEnz.csv mapping)
    - Whether each substrate has at least one enzyme present

  Transporter coverage:
    - Total transporter gene assignments across all taxa
    - Number of unique transporter types present in at least one taxon
    - Average number of transporter genes per taxon

  HSP coverage:
    - Proportion of taxa with at least one HSP gene
    - Community mean HSP constitutive production rate (all taxa, including non-producers)
    - Community mean HSP constitutive production rate (producers only)
    - Community mean HSP inducible production rate (all taxa)
    - Community mean HSP inducible production rate (producers only)

Output
------
  <output-dir>/community_summary.csv   -- all metrics as a two-column key/value table
  <output-dir>/substrate_coverage.csv  -- per-substrate enzyme counts
  Printed report to stdout

Usage
-----
    python analysis/community_summary.py \\
        --community-dir community_pool/communities/community_0001 \\
        --input-dir     input \\
        --output-dir    community_pool/communities/community_0001/summary
"""

import argparse
import os
import sys
import numpy as np
import pandas as pd
from pathlib import Path


# ---------------------------------------------------------------------------
# Loaders
# ---------------------------------------------------------------------------

def load_community(community_dir):
    """Load all trait CSVs needed for community-level summaries."""
    cdir = Path(community_dir)
    if not cdir.is_dir():
        print(f"ERROR: community directory '{cdir}' does not exist.")
        sys.exit(1)

    def csv(name):
        p = cdir / f"{name}.csv"
        if not p.exists():
            raise FileNotFoundError(
                f"Expected file '{p}' not found. "
                f"Was this community generated by assemble_communities.py?"
            )
        return pd.read_csv(p, header=0, index_col=0)

    return {
        'EnzGenes':          csv('EnzGenes'),
        'UptakeGenes':       csv('UptakeGenes'),
        'HSPGenes':          csv('HSPGenes'),
        'HSPProdConsti_trait': csv('HSPProdConsti_trait'),
        'HSPProdInduci_trait': csv('HSPProdInduci_trait'),
    }


def load_enzyme_substrate_map(req_enz_path):
    """
    Load ReqEnz.csv and extract the enzyme-substrate mapping.
    ReqEnz is grid-expanded (n_cells × n_substrates rows, n_enzymes cols).
    One set of substrate rows is sufficient — use the first grid cell.
    Returns a DataFrame (n_substrates × n_enzymes) with 1 where enzyme
    targets that substrate, or None if the file is not found.

    ReqEnz.csv is produced by assemble_communities.py and saved to the root
    of the community pool output directory (sibling of the communities/ folder).
    """
    req_enz_path = Path(req_enz_path)
    if not req_enz_path.exists():
        print(f"WARNING: ReqEnz.csv not found at '{req_enz_path}'. "
              f"Substrate coverage will be skipped.")
        return None

    df = pd.read_csv(req_enz_path, header=0, index_col=[0, 1])
    # Extract first grid cell and deduplicate — ReqEnz is grid-expanded so
    # the same substrate rows repeat once per cell. Take unique substrates only.
    first_set = df.index.get_level_values(0)[0]
    mapping   = df.loc[first_set]
    # Drop duplicate substrate rows (same substrate may appear multiple times)
    mapping   = mapping[~mapping.index.duplicated(keep='first')]
    return mapping


# ---------------------------------------------------------------------------
# Summary computation
# ---------------------------------------------------------------------------

def compute_summary(data, enz_substrate_map):
    """
    Compute all community-level metrics. Returns:
      metrics         -- dict of scalar metrics
      substrate_df    -- DataFrame of per-substrate enzyme counts (or None)
    """
    EnzGenes    = data['EnzGenes'].astype(int)
    UptakeGenes = data['UptakeGenes'].astype(int)
    HSPGenes    = data['HSPGenes'].astype(int)

    # Squeeze trait series — they may be (n_taxa, 1) DataFrames or Series
    hsp_consti = data['HSPProdConsti_trait'].squeeze()
    hsp_induci = data['HSPProdInduci_trait'].squeeze()

    n_taxa      = len(EnzGenes)
    hsp_present = HSPGenes.sum(axis=1) > 0   # bool Series, True if taxon has HSP gene

    metrics = {}

    # ── Enzyme metrics ───────────────────────────────────────────────────────
    enz_per_taxon = EnzGenes.sum(axis=1)           # n genes per taxon
    enz_per_gene  = EnzGenes.sum(axis=0)            # n taxa carrying each gene

    metrics['enz_total_assignments']  = int(enz_per_taxon.sum())
    metrics['enz_unique_genes']       = int((enz_per_gene > 0).sum())
    metrics['enz_total_possible']     = EnzGenes.shape[1]
    metrics['enz_mean_per_taxon']     = round(float(enz_per_taxon.mean()), 4)
    metrics['enz_sd_per_taxon']       = round(float(enz_per_taxon.std()),  4)
    metrics['enz_min_per_taxon']      = int(enz_per_taxon.min())
    metrics['enz_max_per_taxon']      = int(enz_per_taxon.max())

    # ── Transporter metrics ──────────────────────────────────────────────────
    upt_per_taxon = UptakeGenes.sum(axis=1)
    upt_per_type  = UptakeGenes.sum(axis=0)

    metrics['upt_total_assignments']  = int(upt_per_taxon.sum())
    metrics['upt_unique_types']       = int((upt_per_type > 0).sum())
    metrics['upt_total_possible']     = UptakeGenes.shape[1]
    metrics['upt_mean_per_taxon']     = round(float(upt_per_taxon.mean()), 4)
    metrics['upt_sd_per_taxon']       = round(float(upt_per_taxon.std()),  4)
    metrics['upt_min_per_taxon']      = int(upt_per_taxon.min())
    metrics['upt_max_per_taxon']      = int(upt_per_taxon.max())

    # ── HSP metrics ──────────────────────────────────────────────────────────
    n_producers = int(hsp_present.sum())
    metrics['hsp_n_producers']         = n_producers
    metrics['hsp_n_non_producers']     = n_taxa - n_producers
    metrics['hsp_proportion_producers']= round(n_producers / n_taxa, 4)

    # All taxa (non-producers contribute 0)
    metrics['hsp_consti_mean_all']     = round(float(hsp_consti.mean()), 6)
    metrics['hsp_consti_sd_all']       = round(float(hsp_consti.std()),  6)
    metrics['hsp_induci_mean_all']     = round(float(hsp_induci.mean()), 6)
    metrics['hsp_induci_sd_all']       = round(float(hsp_induci.std()),  6)

    # Producers only
    if n_producers > 0:
        metrics['hsp_consti_mean_producers'] = round(float(hsp_consti[hsp_present].mean()), 6)
        metrics['hsp_consti_sd_producers']   = round(float(hsp_consti[hsp_present].std()),  6)
        metrics['hsp_induci_mean_producers'] = round(float(hsp_induci[hsp_present].mean()), 6)
        metrics['hsp_induci_sd_producers']   = round(float(hsp_induci[hsp_present].std()),  6)
    else:
        metrics['hsp_consti_mean_producers'] = float('nan')
        metrics['hsp_consti_sd_producers']   = float('nan')
        metrics['hsp_induci_mean_producers'] = float('nan')
        metrics['hsp_induci_sd_producers']   = float('nan')

    # ── Substrate coverage ───────────────────────────────────────────────────
    substrate_df = None
    if enz_substrate_map is not None:
        # Align enzyme columns between community and mapping
        # (community may have subset of enzymes if some gene pool enzymes absent)
        common_enzymes = enz_substrate_map.columns.intersection(EnzGenes.columns)
        mapping_aligned = enz_substrate_map[common_enzymes]
        genes_aligned   = EnzGenes[common_enzymes]

        # For each substrate: which enzymes target it?
        # community_enzymes_for_substrate = enzymes present in community AND target substrate
        rows = []
        community_has = genes_aligned.sum(axis=0) > 0   # Series (n_enzymes,) bool

        for substrate in mapping_aligned.index:
            row_data = mapping_aligned.loc[substrate]
            # Guard against duplicate index returning a DataFrame instead of Series
            if isinstance(row_data, pd.DataFrame):
                row_data = row_data.iloc[0]
            targets_substrate = row_data                                 # Series (n_enzymes,) 0/1
            enzymes_present   = (targets_substrate.astype(bool) & community_has)

            n_enzymes_targeting   = int(targets_substrate.astype(int).sum())   # total possible
            n_enzymes_in_community= int(enzymes_present.sum())                 # present in community
            n_taxa_with_any       = int(
                genes_aligned.loc[:, targets_substrate.astype(bool)].sum(axis=1).gt(0).sum()
            )

            rows.append({
                'substrate':              substrate,
                'n_enzymes_targeting':    n_enzymes_targeting,
                'n_enzymes_in_community': n_enzymes_in_community,
                'n_taxa_with_any':        n_taxa_with_any,
                'substrate_covered':      n_enzymes_in_community > 0,
            })

        substrate_df = pd.DataFrame(rows).set_index('substrate')

        # Add substrate coverage summary to metrics
        n_substrates      = len(substrate_df)
        n_covered         = int(substrate_df['substrate_covered'].sum())
        metrics['substrate_total']   = n_substrates
        metrics['substrate_covered'] = n_covered
        metrics['substrate_missing'] = n_substrates - n_covered

    return metrics, substrate_df


# ---------------------------------------------------------------------------
# Reporting
# ---------------------------------------------------------------------------

def print_report(metrics, substrate_df, community_dir):
    print(f"\n{'='*60}")
    print(f"Community Summary: {Path(community_dir).name}")
    print(f"{'='*60}")

    print(f"\n--- Enzyme Genes ---")
    print(f"  Total assignments (taxa × genes)  : {metrics['enz_total_assignments']}")
    print(f"  Unique genes present               : {metrics['enz_unique_genes']} / {metrics['enz_total_possible']}")
    print(f"  Mean per taxon (SD)               : {metrics['enz_mean_per_taxon']} ({metrics['enz_sd_per_taxon']})")
    print(f"  Range per taxon                   : {metrics['enz_min_per_taxon']} – {metrics['enz_max_per_taxon']}")

    print(f"\n--- Monomer Transporter Genes ---")
    print(f"  Total assignments (taxa × types)  : {metrics['upt_total_assignments']}")
    print(f"  Unique types present               : {metrics['upt_unique_types']} / {metrics['upt_total_possible']}")
    print(f"  Mean per taxon (SD)               : {metrics['upt_mean_per_taxon']} ({metrics['upt_sd_per_taxon']})")
    print(f"  Range per taxon                   : {metrics['upt_min_per_taxon']} – {metrics['upt_max_per_taxon']}")

    print(f"\n--- HSP ---")
    print(f"  Producers (proportion)            : {metrics['hsp_n_producers']} ({metrics['hsp_proportion_producers']:.1%})")
    print(f"  Non-producers                     : {metrics['hsp_n_non_producers']}")
    print(f"  Constitutive rate — all taxa      : mean={metrics['hsp_consti_mean_all']}  SD={metrics['hsp_consti_sd_all']}")
    print(f"  Constitutive rate — producers     : mean={metrics['hsp_consti_mean_producers']}  SD={metrics['hsp_consti_sd_producers']}")
    print(f"  Inducible rate — all taxa         : mean={metrics['hsp_induci_mean_all']}  SD={metrics['hsp_induci_sd_all']}")
    print(f"  Inducible rate — producers        : mean={metrics['hsp_induci_mean_producers']}  SD={metrics['hsp_induci_sd_producers']}")

    if substrate_df is not None:
        print(f"\n--- Substrate Coverage ---")
        print(f"  Substrates covered                : {metrics['substrate_covered']} / {metrics['substrate_total']}")
        if metrics['substrate_missing'] > 0:
            missing = substrate_df[~substrate_df['substrate_covered']].index.tolist()
            print(f"  *** MISSING substrates            : {', '.join(missing)}")
        print(f"\n  {'Substrate':<20} {'Enz targeting':>14} {'In community':>14} {'Taxa with any':>14} {'Covered':>9}")
        print(f"  {'-'*20} {'-'*14} {'-'*14} {'-'*14} {'-'*9}")
        for sub, row in substrate_df.iterrows():
            covered = 'YES' if row['substrate_covered'] else '*** NO'
            print(f"  {sub:<20} {row['n_enzymes_targeting']:>14} "
                  f"{row['n_enzymes_in_community']:>14} "
                  f"{row['n_taxa_with_any']:>14} "
                  f"{covered:>9}")
    print()


