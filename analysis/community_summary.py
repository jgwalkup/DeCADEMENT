# Main
# ---------------------------------------------------------------------------

def detect_mode(community_dir):
    """
    Determine whether community_dir is:
      'single' -- contains CSV files directly (single community)
      'multi'  -- contains subdirectories that are themselves communities

    A subdirectory is treated as a community if it contains at least one CSV
    file. This prevents output subdirectories (e.g. 'summary/', 'traits/')
    from being mistaken for community directories.
    """
    def looks_like_community(d):
        # A community directory must contain EnzGenes.csv — the canonical
        # marker file written by assemble_communities.py
        return d.is_dir() and (d / 'EnzGenes.csv').exists()

    if any(looks_like_community(c) for c in community_dir.iterdir()):
        return 'multi'
    return 'single'


def run_single(community_dir, enz_substrate_map, output_dir):
    """Run summary for one community directory. Returns (metrics, substrate_df)."""
    data = load_community(community_dir)
    metrics, substrate_df = compute_summary(data, enz_substrate_map)
    print_report(metrics, substrate_df, community_dir)
    return metrics, substrate_df


def main():
    parser = argparse.ArgumentParser(
        description="Compute community-level functional summaries for one or many communities.",
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    parser.add_argument('--community-dir', type=str, required=True,
                        help='Path to a single community directory, or to a '
                             'directory of community subdirectories')
    parser.add_argument('--quiet',         action='store_true',
                        help='Suppress per-community progress messages')
    parser.add_argument('--output-dir',    type=str, default=None,
                        help='Output directory for summary CSVs. '
                             'Single mode default: <community-dir>/summary. '
                             'Multi mode default: <community-dir>/summary')
    args = parser.parse_args()

    community_dir = Path(args.community_dir)

    if not community_dir.is_dir():
        print(f"ERROR: --community-dir '{community_dir}' does not exist.")
        sys.exit(1)

    # ReqEnz.csv is saved by assemble_communities.py to the root of the
    # community pool output directory. In single mode that is the parent of
    # community_dir; in multi mode it is community_dir itself.
    mode = detect_mode(community_dir)
    if mode == 'single':
        req_enz_path = community_dir.parent / 'ReqEnz.csv'
    else:
        req_enz_path = community_dir / 'ReqEnz.csv'

    enz_substrate_map = load_enzyme_substrate_map(req_enz_path)

    # ── Single-community mode ────────────────────────────────────────────────
    if mode == 'single':
        output_dir = Path(args.output_dir) if args.output_dir else community_dir / 'summary'
        output_dir.mkdir(parents=True, exist_ok=True)

        metrics, substrate_df = run_single(community_dir, enz_substrate_map, output_dir)

        metrics_df = pd.DataFrame(
            metrics.items(), columns=['metric', 'value']
        ).set_index('metric')
        metrics_path = output_dir / 'community_summary.csv'
        metrics_df.to_csv(metrics_path)
        print(f"Saved: {metrics_path}")

        if substrate_df is not None:
            sub_path = output_dir / 'substrate_coverage.csv'
            substrate_df.to_csv(sub_path)
            print(f"Saved: {sub_path}")

    # ── Multi-community mode ─────────────────────────────────────────────────
    else:
        output_dir = Path(args.output_dir) if args.output_dir else community_dir / 'summary'
        output_dir.mkdir(parents=True, exist_ok=True)

        # Collect all subdirectories, sorted for deterministic column order
        comm_dirs = sorted(
            [c for c in community_dir.iterdir() if c.is_dir()],
            key=lambda p: p.name
        )
        if not comm_dirs:
            print(f"ERROR: no subdirectories found in '{community_dir}'.")
            sys.exit(1)

        print(f"Multi-community mode: {len(comm_dirs)} communities found.")

        all_metrics    = {}   # {community_name: metrics_dict}
        all_substrates = {}   # {community_name: substrate_df}

        for cdir in comm_dirs:
            name = cdir.name
            if not args.quiet:
                print(f"  Processing: {name}")
            try:
                data = load_community(cdir)
                metrics, substrate_df = compute_summary(data, enz_substrate_map)
                all_metrics[name]    = metrics
                all_substrates[name] = substrate_df
            except Exception as e:
                print(f"  WARNING: could not process '{name}': {e}")
                continue

        if not all_metrics:
            print("ERROR: no communities could be processed.")
            sys.exit(1)

        # ── Combined metrics table ───────────────────────────────────────────
        # Rows = metric names, columns = community names
        combined_metrics = pd.DataFrame(all_metrics)
        combined_metrics.index.name = 'metric'
        metrics_path = output_dir / 'all_communities_summary.csv'
        combined_metrics.to_csv(metrics_path)
        print(f"Saved: {metrics_path}  ({combined_metrics.shape[0]} metrics × {combined_metrics.shape[1]} communities)")

        # ── Combined substrate coverage table ────────────────────────────────
        # Build a MultiIndex: (substrate, column) × community
        # Flatten to wide format: substrate as row index,
        # columns = (community, metric) pairs
        sub_frames = {
            name: df for name, df in all_substrates.items()
            if df is not None
        }
        if sub_frames:
            combined_sub = pd.concat(sub_frames, axis=1)
            # combined_sub has MultiIndex columns: (community_name, metric)
            sub_path = output_dir / 'all_communities_substrate_coverage.csv'
            combined_sub.to_csv(sub_path)
            print(f"Saved: {sub_path}  "
                  f"({len(sub_frames)} communities × "
                  f"{combined_sub.shape[0]} substrates)")


if __name__ == '__main__':
    main()
