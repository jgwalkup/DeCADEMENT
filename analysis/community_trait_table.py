"""
community_trait_table.py
========================
Generate a full per-taxon trait table for a single community directory
produced by assemble_communities.py. Outputs:

  Per-type CSVs (one per trait category):
    <output-dir>/traits_enzymes.csv       -- enzyme investment matrix (n_taxa × n_enzymes)
    <output-dir>/traits_hsp.csv           -- HSP investment matrix (n_taxa × n_HSP)
    <output-dir>/traits_transporters.csv  -- transporter investment matrix (n_taxa × n_uptake)

  Combined wide table:
    <output-dir>/traits_combined.csv      -- all columns concatenated, taxa as rows

Column structure
----------------
  traits_enzymes.csv:
    EnzGene_Enz1 … EnzGene_Enz50   -- gene presence/absence (0/1)
    EnzConsti_Enz1 … EnzConsti_Enz50 -- constitutive investment (rate × gene)
    EnzInduci_Enz1 … EnzInduci_Enz50 -- inducible investment (rate × gene)

  traits_hsp.csv:
    HSPGene_HSP1 …                  -- gene presence/absence (0/1)
    HSPConsti_HSP1 …                -- constitutive investment (rate × gene)
    HSPInduci_HSP1 …                -- inducible investment (rate × gene)

  traits_transporters.csv:
    Upt_NH4, Upt_PO4, Upt_Mon_Cellulose … -- transporter investment (UptakeGenesCost)

  traits_combined.csv:
    All of the above concatenated, taxa as rows.

Usage
-----
    python analysis/community_trait_table.py \\
        --community-dir community_pool/communities/community_0001 \\
        --output-dir    community_pool/communities/community_0001/traits
"""

import argparse
import os
import sys
import pandas as pd
from pathlib import Path


# ---------------------------------------------------------------------------
# Loaders
# ---------------------------------------------------------------------------

def load_community(community_dir):
    """Load all relevant trait CSVs from a community directory."""
    cdir = Path(community_dir)
    if not cdir.is_dir():
        print(f"ERROR: community directory '{cdir}' does not exist.")
        sys.exit(1)

    def csv(name):
        p = cdir / f"{name}.csv"
        if not p.exists():
            raise FileNotFoundError(
                f"Expected file '{p}' not found. "
                f"Was this community generated by assemble_communities.py?"
            )
        return pd.read_csv(p, header=0, index_col=0)

    return {
        # Gene presence/absence
        'EnzGenes':       csv('EnzGenes'),
        'HSPGenes':       csv('HSPGenes'),
        'UptakeGenes':    csv('UptakeGenes'),
        # Full investment matrices
        'EnzProdConstit': csv('EnzProdConstit'),
        'EnzProdInduce':  csv('EnzProdInduce'),
        'HSPProdConsti':  csv('HSPProdConsti'),
        'HSPProdInduci':  csv('HSPProdInduci'),
        'UptakeGenesCost':csv('UptakeGenesCost'),
    }


# ---------------------------------------------------------------------------
# Table builders
# ---------------------------------------------------------------------------

def build_enzyme_table(data):
    """
    Returns a DataFrame with:
      EnzGene_*    -- gene presence/absence
      EnzConsti_*  -- constitutive investment matrix
      EnzInduci_*  -- inducible investment matrix
    """
    genes   = data['EnzGenes'].add_prefix('EnzGene_')
    consti  = data['EnzProdConstit'].add_prefix('EnzConsti_')
    induci  = data['EnzProdInduce'].add_prefix('EnzInduci_')
    return pd.concat([genes, consti, induci], axis=1)


def build_hsp_table(data):
    """
    Returns a DataFrame with:
      HSPGene_*    -- gene presence/absence
      HSPConsti_*  -- constitutive investment matrix
      HSPInduci_*  -- inducible investment matrix
    """
    genes   = data['HSPGenes'].add_prefix('HSPGene_')
    consti  = data['HSPProdConsti'].add_prefix('HSPConsti_')
    induci  = data['HSPProdInduci'].add_prefix('HSPInduci_')
    return pd.concat([genes, consti, induci], axis=1)


def build_transporter_table(data):
    """
    Returns a DataFrame with transporter investment columns prefixed Upt_.
    Values come from UptakeGenesCost (already = UptakeGenes × per-gene cost).
    """
    return data['UptakeGenesCost'].add_prefix('Upt_')


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------

def main():
    parser = argparse.ArgumentParser(
        description="Generate per-taxon trait tables for a DeCA-DEMENT community.",
        formatter_class=argparse.ArgumentDefaultsHelpFormatter,
    )
    parser.add_argument('--community-dir', type=str, required=True,
                        help='Path to community directory (produced by assemble_communities.py)')
    parser.add_argument('--output-dir',    type=str, default=None,
                        help='Output directory for trait CSVs '
                             '(default: <community-dir>/traits)')
    args = parser.parse_args()

    community_dir = Path(args.community_dir)
    output_dir    = Path(args.output_dir) if args.output_dir else community_dir / 'traits'
    output_dir.mkdir(parents=True, exist_ok=True)

    print(f"Loading community: {community_dir}")
    data = load_community(community_dir)

    n_taxa = len(data['EnzGenes'])
    print(f"  Taxa: {n_taxa}")

    # Build per-type tables
    enz_table = build_enzyme_table(data)
    hsp_table = build_hsp_table(data)
    upt_table = build_transporter_table(data)

    # Save per-type CSVs
    enz_path = output_dir / 'traits_enzymes.csv'
    hsp_path = output_dir / 'traits_hsp.csv'
    upt_path = output_dir / 'traits_transporters.csv'
    cmb_path = output_dir / 'traits_combined.csv'

    enz_table.to_csv(enz_path)
    hsp_table.to_csv(hsp_path)
    upt_table.to_csv(upt_path)

    print(f"  Saved: {enz_path.name}  ({enz_table.shape[1]} columns)")
    print(f"  Saved: {hsp_path.name}  ({hsp_table.shape[1]} columns)")
    print(f"  Saved: {upt_path.name}  ({upt_table.shape[1]} columns)")

    # Combined wide table
    combined = pd.concat([enz_table, hsp_table, upt_table], axis=1)
    combined.to_csv(cmb_path)
    print(f"  Saved: {cmb_path.name}  ({combined.shape[1]} total columns)")


if __name__ == '__main__':
    main()
